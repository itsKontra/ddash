// Command dashboard writes the App icons' data from homarr-labs/dashboard-icons
// at the pinned commit (`make generate`):
//
//   - core/icons/dashboard-icons/aliases.json, every icon's name and search
//     aliases from the upstream metadata.json, which ../gzip then compresses;
//   - packages/ui/src/dashboard-icons.ts, the commit, so AppIcon loads the
//     logos from jsDelivr at the same commit the search knows.
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"strings"
)

// commit pins dashboard-icons; bump it to pick up new icons.
const commit = "d3b9234dd56f3af5862f06741f0dce101193b3df"

func main() {
	url := fmt.Sprintf("https://cdn.jsdelivr.net/gh/homarr-labs/dashboard-icons@%s/metadata.json", commit)
	res, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, res.Status)
	}
	b, err := io.ReadAll(res.Body)
	if err != nil {
		log.Fatal(err)
	}
	var meta map[string]struct {
		Aliases []string `json:"aliases"`
	}
	if err := json.Unmarshal(b, &meta); err != nil {
		log.Fatal(err)
	}
	aliases := make(map[string][]string, len(meta))
	for name, m := range meta {
		a := []string{}
		for _, s := range m.Aliases {
			a = append(a, strings.ToLower(s))
		}
		aliases[name] = a
	}
	// encoding/json sorts map keys, so the same commit gives the same bytes.
	j, err := json.Marshal(aliases)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("core/icons/dashboard-icons/aliases.json", j, 0o644); err != nil {
		log.Fatal(err)
	}
	ts := "// Generated by core/icons/dashboard. Do not edit.\n\n" +
		"/** The homarr-labs/dashboard-icons commit the core's App icon search and AppIcon's logos share. */\n" +
		fmt.Sprintf("export const dashboardIconsCommit = %q;\n", commit)
	if err := os.WriteFile("packages/ui/src/dashboard-icons.ts", []byte(ts), 0o644); err != nil {
		log.Fatal(err)
	}
}
