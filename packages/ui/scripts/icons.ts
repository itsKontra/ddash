// Generates the icon data from the pinned lucide-static (the root
// package.json): the core's embedded icon nodes (core/icons) and the
// IconName union @ddash/ui's Icon takes. `make generate` runs it; both
// outputs are committed.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { gzipSync } from "node:zlib";

const require = createRequire(import.meta.url);
const root = new URL("../../../", import.meta.url);
const lucide = require.resolve("lucide-static/package.json");
const { version } = JSON.parse(readFileSync(lucide, "utf8")) as { version: string };
const nodes = JSON.parse(readFileSync(new URL("icon-nodes.json", `file://${lucide}`), "utf8")) as Record<string, unknown>;
const names = Object.keys(nodes).sort();

writeFileSync(new URL("core/icons/lucide/icon-nodes.json.gz", root), gzipSync(JSON.stringify(nodes), { level: 9 }));
writeFileSync(
  new URL("packages/ui/src/icon-names.ts", root),
  `// Generated by packages/ui/scripts/icons.ts from lucide-static ${version}. Do not edit.\n\n` +
    `/** Every lucide icon name the core serves. */\n` +
    `export type IconName =\n${names.map((n) => `  | ${JSON.stringify(n)}`).join("\n")};\n`,
);
